package com.descope.sdk.auth;

import com.descope.enums.NOTPProvider;
import com.descope.exception.DescopeException;
import com.descope.model.auth.AuthenticationInfo;
import com.descope.model.auth.UpdateOptions;
import com.descope.model.magiclink.LoginOptions;
import com.descope.model.magiclink.SignUpOptions;
import com.descope.model.notp.NOTPResponse;
import com.descope.model.user.User;
import java.util.Map;

public interface NOTPService {
  /**
   * Use to login a user by having them send a message through the given provider (e.g. WhatsApp).
   *
   * @param provider     - {@link NOTPProvider NOTPProvider} the user sends the message with
   * @param loginId      - User login ID, optional since it can be taken from the provider
   * @param loginOptions - {@link LoginOptions LoginOptions}
   * @return {@link NOTPResponse} with the pendingRef, a redirect URL to the provider app and a QR code image
   * @throws DescopeException - error upon failure
   */
  NOTPResponse signIn(NOTPProvider provider, String loginId, LoginOptions loginOptions) throws DescopeException;

  /**
   * Use to login a user by having them send a message through the given provider (e.g. WhatsApp).
   *
   * @param provider     - {@link NOTPProvider NOTPProvider} the user sends the message with
   * @param loginId      - User login ID, optional since it can be taken from the provider
   * @param loginOptions - {@link LoginOptions LoginOptions}
   * @param refreshToken - when doing step-up or mfa then we need current session token
   * @return {@link NOTPResponse} with the pendingRef, a redirect URL to the provider app and a QR code image
   * @throws DescopeException - error upon failure
   */
  NOTPResponse signIn(NOTPProvider provider, String loginId, LoginOptions loginOptions, String refreshToken)
      throws DescopeException;

  /**
   * Use to create a new user that verifies by sending a message through the given provider (e.g. WhatsApp).
   *
   * @param provider - {@link NOTPProvider NOTPProvider} the user sends the message with
   * @param loginId  - User login ID, a phone number
   * @param user     - {@link User User}, its phone defaults to the login ID
   * @return {@link NOTPResponse} with the pendingRef, a redirect URL to the provider app and a QR code image
   * @throws DescopeException - error upon failure
   */
  NOTPResponse signUp(NOTPProvider provider, String loginId, User user) throws DescopeException;

  /**
   * Use to create a new user that verifies by sending a message through the given provider (e.g. WhatsApp).
   *
   * @param provider      - {@link NOTPProvider NOTPProvider} the user sends the message with
   * @param loginId       - User login ID, a phone number
   * @param user          - {@link User User}, its phone defaults to the login ID
   * @param signUpOptions - optional claims and template strings
   * @return {@link NOTPResponse} with the pendingRef, a redirect URL to the provider app and a QR code image
   * @throws DescopeException - error upon failure
   */
  NOTPResponse signUp(NOTPProvider provider, String loginId, User user, SignUpOptions signUpOptions)
      throws DescopeException;

  /**
   * Use to login in using loginID, if user does not exist, a new user will be created.
   *
   * @param provider - {@link NOTPProvider NOTPProvider} the user sends the message with
   * @param loginId  - User login ID, optional since it can be taken from the provider
   * @return {@link NOTPResponse} with the pendingRef, a redirect URL to the provider app and a QR code image
   * @throws DescopeException - error upon failure
   */
  NOTPResponse signUpOrIn(NOTPProvider provider, String loginId) throws DescopeException;

  /**
   * Use to login in using loginID, if user does not exist, a new user will be created.
   *
   * @param provider      - {@link NOTPProvider NOTPProvider} the user sends the message with
   * @param loginId       - User login ID, optional since it can be taken from the provider
   * @param signUpOptions - optional claims and template strings
   * @return {@link NOTPResponse} with the pendingRef, a redirect URL to the provider app and a QR code image
   * @throws DescopeException - error upon failure
   */
  NOTPResponse signUpOrIn(NOTPProvider provider, String loginId, SignUpOptions signUpOptions)
      throws DescopeException;

  /**
   * Use to get a session that was generated by a SignIn/SignUp/SignUpOrIn/UpdateUserPhone request, once the
   * user sent the message.
   *
   * @param pendingRef - pending Ref returned by the previous request
   * @return authentication info
   * @throws DescopeException - error upon failure, including while the user has not sent the message yet
   */
  AuthenticationInfo getSession(String pendingRef) throws DescopeException;

  /**
   * Use to update a user's phone, verified by the user sending a message through the given provider.
   *
   * @param provider      - {@link NOTPProvider NOTPProvider} the user sends the message with
   * @param loginId       - User login ID
   * @param phone         - User phone
   * @param refreshToken  - refresh token to perform the update
   * @param updateOptions - update options for the update
   * @return {@link NOTPResponse} with the pendingRef, a redirect URL to the provider app and a QR code image
   * @throws DescopeException - error upon failure
   */
  NOTPResponse updateUserPhone(NOTPProvider provider, String loginId, String phone, String refreshToken,
      UpdateOptions updateOptions) throws DescopeException;

  /**
   * Use to update a user's phone, verified by the user sending a message through the given provider.
   *
   * @param provider        - {@link NOTPProvider NOTPProvider} the user sends the message with
   * @param loginId         - User login ID
   * @param phone           - User phone
   * @param refreshToken    - refresh token to perform the update
   * @param updateOptions   - update options for the update
   * @param templateOptions - template options for the message
   * @return {@link NOTPResponse} with the pendingRef, a redirect URL to the provider app and a QR code image
   * @throws DescopeException - error upon failure
   */
  NOTPResponse updateUserPhone(NOTPProvider provider, String loginId, String phone, String refreshToken,
      UpdateOptions updateOptions, Map<String, String> templateOptions) throws DescopeException;
}
