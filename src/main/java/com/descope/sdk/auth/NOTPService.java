package com.descope.sdk.auth;

import com.descope.exception.DescopeException;
import com.descope.model.auth.AuthenticationInfo;
import com.descope.model.magiclink.LoginOptions;
import com.descope.model.magiclink.SignUpOptions;
import com.descope.model.notp.NOTPOptions;
import com.descope.model.notp.NOTPResponse;
import com.descope.model.notp.NOTPUpdateOptions;
import com.descope.model.user.User;

/**
 * NOTP authentication: the user sends a message from a messaging app (e.g. WhatsApp) instead of
 * receiving a code. Show the user the redirect URL or QR code image from the response, then poll
 * {@link #getSession(String)} with the pending ref until the user has sent the message.
 */
public interface NOTPService {

  /**
   * Use to login a user with NOTP.
   *
   * @param provider     - NOTP provider, e.g. "whatsapp" (max 254 characters)
   * @param loginId      - User login ID, a phone or empty. If empty, the provider's phone number is
   *                     used as the login ID in the verification process
   * @param token        - Refresh token, required when loginOptions has stepup or mfa set
   * @param loginOptions - {@link LoginOptions LoginOptions}, optional
   * @param options      - {@link NOTPOptions NOTPOptions}, optional
   * @return {@link NOTPResponse NOTPResponse}
   * @throws DescopeException - error upon failure
   */
  NOTPResponse signIn(String provider, String loginId, String token, LoginOptions loginOptions,
      NOTPOptions options) throws DescopeException;

  /**
   * Use to create a new user with NOTP.
   *
   * @param provider      - NOTP provider, e.g. "whatsapp" (max 254 characters)
   * @param loginId       - User login ID, a phone or empty. If empty, the provider's phone number is
   *                      used as the login ID in the verification process
   * @param user          - {@link User User}, optional. Its phone defaults to the login ID
   * @param signUpOptions - {@link SignUpOptions SignUpOptions}, optional
   * @param options       - {@link NOTPOptions NOTPOptions}, optional
   * @return {@link NOTPResponse NOTPResponse}
   * @throws DescopeException - error upon failure
   */
  NOTPResponse signUp(String provider, String loginId, User user, SignUpOptions signUpOptions,
      NOTPOptions options) throws DescopeException;

  /**
   * Use to login a user with NOTP. If the user does not exist, a new user will be created.
   *
   * @param provider      - NOTP provider, e.g. "whatsapp" (max 254 characters)
   * @param loginId       - User login ID, a phone or empty. If empty, the provider's phone number is
   *                      used as the login ID in the verification process
   * @param signUpOptions - {@link SignUpOptions SignUpOptions}, optional
   * @param options       - {@link NOTPOptions NOTPOptions}, optional
   * @return {@link NOTPResponse NOTPResponse}
   * @throws DescopeException - error upon failure
   */
  NOTPResponse signUpOrIn(String provider, String loginId, SignUpOptions signUpOptions,
      NOTPOptions options) throws DescopeException;

  /**
   * Use to update the phone of an existing user with NOTP.
   *
   * @param provider      - NOTP provider, e.g. "whatsapp" (max 254 characters)
   * @param loginId       - User login ID
   * @param phone         - New phone, optional
   * @param refreshToken  - Refresh token of the user
   * @param updateOptions - {@link NOTPUpdateOptions NOTPUpdateOptions}, optional
   * @return {@link NOTPResponse NOTPResponse}
   * @throws DescopeException - error upon failure
   */
  NOTPResponse updateUser(String provider, String loginId, String phone, String refreshToken,
      NOTPUpdateOptions updateOptions) throws DescopeException;

  /**
   * Use to get a session that was generated by a NOTP sign-in, sign-up or sign-up-or-in request.
   * A valid session is returned only after the user has sent the verification message.
   *
   * @param pendingRef - Pending reference from the {@link NOTPResponse NOTPResponse} (max 254 characters)
   * @return {@link AuthenticationInfo AuthenticationInfo}
   * @throws DescopeException - error upon failure
   */
  AuthenticationInfo getSession(String pendingRef) throws DescopeException;
}
